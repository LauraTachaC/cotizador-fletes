import pandas as pd
import numpy as np

def cargar_datos(ruta_archivo):
    """Carga el dataset inicial."""
    return pd.read_csv(ruta_archivo)

def eliminar_data_leakage(df):
    """
    Elimina las variables de facturación pos-entrega.
    """
    columnas_prohibidas = [
        'ocean_surcharge', 'final_surcharge', 'land_freight_invoiced',
        'surcharge_discount', 'land_freight_discount', 'ocean_value_change',
        'original_destination', 'original_ocean_value'
    ]
    cols_a_eliminar = [col for col in columnas_prohibidas if col in df.columns]
    return df.drop(columns=cols_a_eliminar)

def aplicar_filtros_basicos(df):
    """
    Filtra los registros con menos de 1 skid para evitar explosión del costo unitario.
    """
    return df[df['total_skids'] >= 1.0].copy()

### Funcion para outliers --PENDIENTE DE VERIFICACION #####
def manejar_outliers_skids(df, estrategia='ninguna'):
    """
    Maneja las órdenes que reportan cantidades de skids imposibles (ej. > 44 en un 40FT).
    Opciones de estrategia: 'eliminar', 'correccion_heuristica', 'imputacion', 'ninguna'.
    """
    # Capacidad máxima teórica según contenedor
    capacidades_max = {'40FT': 44, '20FT': 22, 'LCL': 10}
    df['cap_max'] = df['container_type'].map(capacidades_max).fillna(44)

    mask_outliers = df['total_skids'] > df['cap_max']

    if estrategia == 'eliminar':
        # Opción 1: Exclusión directa (Recomendada para mantener datos limpios)
        df = df[~mask_outliers].copy()

    elif estrategia == 'correccion_heuristica':
        # Opción 2: Correr el punto decimal si fue un error de tipeo (ej. 895 a 8.95)
        def corregir_decimal(val, cap):
            if val > cap:
                if val / 10 <= cap: return val / 10
                elif val / 100 <= cap: return val / 100
                else: return cap
            return val

        df['total_skids'] = df.apply(
            lambda row: corregir_decimal(row['total_skids'], row['cap_max']), axis=1
        )
        # Recalcular el costo unitario (variable objetivo) con los nuevos skids
        df['ocean_cost_per_skid'] = df['ocean_cost'] / df['total_skids']
        df['land_cost_per_skid'] = df['land_cost'] / df['total_skids']

    elif estrategia == 'imputacion':
        # Opción 3: Forzar los outliers a la moda histórica (20 skids para 40FT)
        moda_40ft = 20.0
        df.loc[mask_outliers & (df['container_type'] == '40FT'), 'total_skids'] = moda_40ft
        df['ocean_cost_per_skid'] = df['ocean_cost'] / df['total_skids']
        df['land_cost_per_skid'] = df['land_cost'] / df['total_skids']

    elif estrategia == 'ninguna':
        # Se mantienen los outliers intactos a la espera de decisión de negocio
        pass

    # Limpiar columna auxiliar
    return df.drop(columns=['cap_max'])



def imputar_nulos(df):
    """
    Imputa días de anticipación con la mediana según cliente y contenedor.
    """
    df['lead_time_days'] = df.groupby(['customer_id', 'container_type'])['lead_time_days'].transform(
        lambda x: x.fillna(x.median())
    )
    # Si algún cliente es nuevo y queda en nulo, usamos la mediana global
    df['lead_time_days'] = df['lead_time_days'].fillna(df['lead_time_days'].median())
    return df

