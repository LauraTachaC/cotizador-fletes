import pandas as pd
import numpy as np
import mlflow
import mlflow.xgboost
from xgboost import XGBRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error
import warnings
warnings.filterwarnings('ignore')

# 1. Cargar el conjunto de datos y prepararlo
df = pd.read_csv("ordenes_modelado.csv")

# División temporal (Time-Series Split). Entremiento con 2025 hacia atras. Prueba con 2026
train_df = df[df['order_year'] <= 2025].copy()
test_df = df[df['order_year'] == 2026].copy()

# Variables predictoras
features = [
    'total_skids', 'lead_time_days', 'mes_seno', 'mes_coseno',
    'anticipacion_semanas', 'es_entrada_oeste', 'es_entrada_este',
    'es_destino_interior', 'recogida_en_puerto'
]
cats = ['container_type']

# Transformación de variables categóricas (One-Hot Encoding)
X_train_raw = pd.get_dummies(train_df[features + cats], drop_first=True)
X_test_raw = pd.get_dummies(test_df[features + cats], drop_first=True)
X_train, X_test = X_train_raw.align(X_test_raw, join='left', axis=1, fill_value=0)

y_train = train_df['ocean_cost_per_skid']
y_test = test_df['ocean_cost_per_skid']


# 2. Definir el servidor para llevar el registro de modelos (Ajustar a tu EC2 si es necesario)
# mlflow.set_tracking_uri('http://localhost:5000')

# Registre el experimento
experiment = mlflow.set_experiment("Cotizador-Flete-Maritimo")

with mlflow.start_run(experiment_id=experiment.experiment_id):
    n_estimators = 150
    max_depth = 6
    learning_rate = 0.05
    xgb_model = XGBRegressor(
        n_estimators=n_estimators,
        max_depth=max_depth,
        learning_rate=learning_rate,
        random_state=42
    )

    xgb_model.fit(X_train, np.log1p(y_train))

    predictions_log = xgb_model.predict(X_test)
    predictions = np.expm1(predictions_log)

    mlflow.log_param("num_trees", n_estimators)
    mlflow.log_param("max_depth", max_depth)
    mlflow.log_param("learning_rate", learning_rate)

    mlflow.xgboost.log_model(xgb_model, artifact_path="xgboost-ocean-model")

    mae = mean_absolute_error(y_test, predictions)
    rmse = np.sqrt(mean_squared_error(y_test, predictions))

    mlflow.log_metric("mae", mae)
    mlflow.log_metric("rmse", rmse)

    print(f"Modelo entrenado y registrado con éxito.")
    print(f"MAE: ${mae:.2f}")
    print(f"RMSE: ${rmse:.2f}")